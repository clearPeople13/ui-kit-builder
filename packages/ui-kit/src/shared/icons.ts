export type UiIconName = keyof typeof UI_ICONS

const customIcons = new Map<string, Component>()

export function registerIcon(name: string, icon: Component): void {
  customIcons.set(name, icon)
}

export function unregisterIcon(name: string): void {
  customIcons.delete(name)
}

export function resolveIcon(icon: Component | string | null | undefined): Component | undefined {
  if (!icon) {
    return undefined
  }
  if (typeof icon === 'string') {
    return customIcons.get(icon) ?? (UI_ICONS as Record<string, Component>)[icon]
  }
  return icon
}
